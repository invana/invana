"""SQLAlchemy async models for graph schema storage.

Tables
------
- ``graph_models``               — top-level graph model (schema) container
- ``graph_versions``            — immutable snapshots (draft → active → archived)
- ``property_key_definitions``   — global property keys (name + type), one per version
- ``node_type_definitions``      — node types with inheritance and display metadata
- ``edge_type_definitions``      — edge types with multiplicity and endpoint restrictions
- ``type_property_mappings``     — links property keys to node/edge types
- ``validation_rules``           — per-property-key or per-mapping validation rules
- ``constraint_definitions``     — explicit constraints (unique, exists, node_key) on labels
- ``index_definitions``          — schema-managed indexes
- ``schema_projections``         — records of DDL pushed to graph databases
- ``model_links``                — declared anchors and relationship links between two
                                   published versions (stitch-models.md)
"""

from __future__ import annotations

import uuid
from datetime import UTC, datetime

from sqlalchemy import (
    JSON,
    Boolean,
    DateTime,
    Enum,
    ForeignKey,
    Integer,
    String,
    Text,
    UniqueConstraint,
)
from sqlalchemy.orm import Mapped, mapped_column, relationship

from invana.core.models import Base


def _utcnow() -> datetime:
    return datetime.now(UTC)


def _new_id() -> str:
    return str(uuid.uuid4())


# ---------------------------------------------------------------------------
# Graph Model — a model of the data over the bound DB
# (docs/for-developers/modules/connect-and-model/features/domain-models.md)
#
# A Graph owns many GraphModels. Each is a logical schema/subgraph over the one
# bound physical DB, with its own versioned type tree. ``graph_id`` is nullable
# during the transition off the legacy ``graph_connections.model_id`` 1:1
# pointer; it will be tightened to NOT NULL once creation paths populate it.
# ---------------------------------------------------------------------------


class GraphModel(Base):
    __tablename__ = "graph_models"

    id: Mapped[str] = mapped_column(String(36), primary_key=True, default=_new_id)
    # Owner — many models per Graph. CASCADE so models die with the Graph
    # (not with the connection). Nullable for now; see header note.
    graph_id: Mapped[str | None] = mapped_column(ForeignKey("graphs.id", ondelete="CASCADE"), nullable=True, index=True)
    name: Mapped[str] = mapped_column(String(255), nullable=False)
    description: Mapped[str] = mapped_column(Text, default="")
    # Portable identity (share-a-model.md SM2). The name is local — two Graphs may
    # call the same package different things — so ``package_id`` is what an upgrade
    # resolves against. Stable for the life of the model, and carried in its artefact.
    package_id: Mapped[str] = mapped_column(String(64), nullable=False, default=_new_id, index=True)
    # Where this model came from, when it did not start here: ``file`` for an
    # imported artefact, ``starter`` for one shipped with the distribution
    # (starter-models.md SR1). NULL means it was authored in this Graph.
    import_source: Mapped[str | None] = mapped_column(String(32), nullable=True)
    validation_mode: Mapped[str] = mapped_column(
        Enum("strict", "permissive", name="validation_mode_enum"),
        default="strict",
    )
    # Model lifecycle — distinct from GraphVersion.status (per-version state).
    status: Mapped[str] = mapped_column(
        Enum("draft", "active", "archived", name="model_status_enum"),
        default="draft",
        nullable=False,
    )
    # Provenance / editability. ``introspected`` = the read-only "global" model that
    # mirrors the physical DB (regenerated by introspection, never hand-authored);
    # ``studio`` = authored in the Modeller; ``yaml`` = YAML-managed.
    origin: Mapped[str] = mapped_column(
        Enum("studio", "yaml", "introspected", name="model_origin_enum"),
        default="studio",
        nullable=False,
    )
    # Set ⟺ YAML-managed; NULL = authored in Studio. Single indicator of YAML
    # ownership (no separate ``source`` column).
    yaml_path: Mapped[str | None] = mapped_column(String(1024), nullable=True)
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), default=_utcnow)
    updated_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), default=_utcnow, onupdate=_utcnow)

    versions: Mapped[list[GraphVersion]] = relationship(
        back_populates="schema", cascade="all, delete-orphan", order_by="GraphVersion.created_at"
    )


# ---------------------------------------------------------------------------
# Schema Version
# ---------------------------------------------------------------------------


class GraphVersion(Base):
    __tablename__ = "graph_versions"
    __table_args__ = (UniqueConstraint("model_id", "version", name="uq_graph_version"),)

    id: Mapped[str] = mapped_column(String(36), primary_key=True, default=_new_id)
    model_id: Mapped[str] = mapped_column(ForeignKey("graph_models.id", ondelete="CASCADE"), nullable=False)
    version: Mapped[str | None] = mapped_column(String(32), nullable=True)
    status: Mapped[str] = mapped_column(
        Enum("draft", "active", "archived", name="version_status_enum"),
        default="draft",
    )
    change_summary: Mapped[str] = mapped_column(Text, default="")
    # SHA-256 over the version's canonical artefact body, stamped when it publishes
    # (share-a-model.md SM2). With ``package_id`` it is the version's identity, so the
    # same content arriving under another name is recognised as an upgrade, not a copy.
    content_hash: Mapped[str | None] = mapped_column(String(64), nullable=True, index=True)
    # Which property carries valid time, which carries geography, and which named
    # properties are selectable dimensions
    # (docs/for-developers/modules/connect-and-model/features/domain-models.md DM6):
    #
    #     {"time": {"property": "observed_at"},
    #      "geo":  {"property": "country_iso", "vocab": "iso2"},
    #      "dims": ["channel", "segment"]}
    #
    # Empty is the default and means *nothing is selectable*: a world asking to
    # slice along an axis this version never declared is refused naming the model
    # and the axis, never silently ignored (GV14). Inferring one from a property's
    # name or type would make "which rows did this run see" depend on a guess.
    axes: Mapped[dict] = mapped_column(JSON, nullable=False, default=dict, server_default="{}")
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), default=_utcnow)
    activated_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True), nullable=True)

    schema: Mapped[GraphModel] = relationship(back_populates="versions")
    property_keys: Mapped[list[PropertyKeyDefinition]] = relationship(
        back_populates="version", cascade="all, delete-orphan"
    )
    node_types: Mapped[list[NodeTypeDefinition]] = relationship(back_populates="version", cascade="all, delete-orphan")
    edge_types: Mapped[list[EdgeTypeDefinition]] = relationship(back_populates="version", cascade="all, delete-orphan")
    constraints: Mapped[list[ConstraintDefinition]] = relationship(
        back_populates="version", cascade="all, delete-orphan"
    )
    indexes: Mapped[list[IndexDefinition]] = relationship(back_populates="version", cascade="all, delete-orphan")
    projections: Mapped[list[SchemaProjection]] = relationship(back_populates="version", cascade="all, delete-orphan")


# ---------------------------------------------------------------------------
# Property Key Definition (global per version)
# ---------------------------------------------------------------------------


class PropertyKeyDefinition(Base):
    """A global property key — defined once per version, used by many types."""

    __tablename__ = "property_key_definitions"
    __table_args__ = (UniqueConstraint("version_id", "name", name="uq_version_property_key"),)

    id: Mapped[str] = mapped_column(String(36), primary_key=True, default=_new_id)
    version_id: Mapped[str] = mapped_column(ForeignKey("graph_versions.id", ondelete="CASCADE"), nullable=False)
    name: Mapped[str] = mapped_column(String(255), nullable=False)
    type: Mapped[str] = mapped_column(String(64), nullable=False, default="string")
    value_cardinality: Mapped[str] = mapped_column(
        Enum("SINGLE", "LIST", "SET", name="value_cardinality_enum"),
        default="SINGLE",
    )
    description: Mapped[str] = mapped_column(Text, default="")

    version: Mapped[GraphVersion] = relationship(back_populates="property_keys")
    mappings: Mapped[list[TypePropertyMapping]] = relationship(
        back_populates="property_key", cascade="all, delete-orphan"
    )
    validation_rules: Mapped[list[ValidationRule]] = relationship(
        back_populates="property_key",
        cascade="all, delete-orphan",
        foreign_keys="ValidationRule.property_key_id",
    )


