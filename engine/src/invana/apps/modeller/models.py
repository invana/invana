# ---------------------------------------------------------------------------
# Model Link — a declared anchor or relationship between two published versions
# (docs/for-developers/modules/connect-and-model/features/stitch-models.md)
#
# Nothing here is inferred (ST1). An anchor says two types are the same entity and
# is resolved by a named identity property; it never merges the two nodes (ST2). A
# relationship link declares a cross-model edge type whose records arrive in a
# dataset like any other data (ST4). The global model is the read-time union of the
# published versions plus these rows — it is never itself stored (ST3).
# ---------------------------------------------------------------------------


class ModelLink(Base):
    __tablename__ = "model_links"
    __table_args__ = (
        UniqueConstraint(
            "graph_id",
            "kind",
            "source_version_id",
            "source_type",
            "target_version_id",
            "target_type",
            "edge_type",
            name="uq_model_link",
        ),
    )

    id: Mapped[str] = mapped_column(String(36), primary_key=True, default=_new_id)
    graph_id: Mapped[str] = mapped_column(ForeignKey("graphs.id", ondelete="CASCADE"), nullable=False, index=True)
    kind: Mapped[str] = mapped_column(Enum("anchor", "relationship", name="model_link_kind_enum"), nullable=False)

    # Staged or active (stitch-models.md ST21). A declared stitch lands *staged*:
    # the row exists, so it survives a reload and anyone opening the Graph sees
    # it, but the derived global model unions active rows only — so nothing a
    # question can reach changes until somebody commits. This is deliberately not
    # the model's staged set, which is the live diff between a draft and the
    # version it replaces and records nothing; a stitch belongs to no version, so
    # it has no draft to diff.
    status: Mapped[str] = mapped_column(
        Enum("staged", "active", name="model_link_status_enum"),
        default="staged",
        nullable=False,
    )

    # Both endpoints name a *published* version (ST7 / "links only bind published
    # versions"), so a link always points at something immutable.
    source_version_id: Mapped[str] = mapped_column(ForeignKey("graph_versions.id", ondelete="CASCADE"), nullable=False)
    source_type: Mapped[str] = mapped_column(String(255), nullable=False)
    target_version_id: Mapped[str] = mapped_column(ForeignKey("graph_versions.id", ondelete="CASCADE"), nullable=False)
    target_type: Mapped[str] = mapped_column(String(255), nullable=False)

    # A key on each side, and how the two compare (ST26). One property name
    # assumed to hold on both sides is a rule that only survives when the two
    # models were authored together, which is the one case stitching is not for:
    # `Company.ticker` and `Stock.nse_symbol` are the ordinary shape. The pair
    # reads *same entity* on an anchor and *where the edge attaches* on a
    # relationship, because it is the same question both times. No score, ever (C3).
    source_property: Mapped[str | None] = mapped_column(String(255), nullable=True)
    target_property: Mapped[str | None] = mapped_column(String(255), nullable=True)
    identity_match: Mapped[str] = mapped_column(
        Enum("exact", "case_insensitive", name="model_link_match_enum"),
        default="exact",
        nullable=False,
    )

    # relationship: the edge type declared between the two, and — when the edge
    # is its own fact rather than a key the records already carry — the model
    # whose records ship it. Keys or a source model, never both (ST27).
    edge_type: Mapped[str | None] = mapped_column(String(255), nullable=True)
    source_model_id: Mapped[str | None] = mapped_column(String(36), nullable=True)

    description: Mapped[str] = mapped_column(Text, default="")
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), default=_utcnow)
    updated_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), default=_utcnow, onupdate=_utcnow)
